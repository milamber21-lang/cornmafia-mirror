function parseArgs(argv) {
	const options = {
		patchCode: "",
		scanBatchId: null,
		patchesRootRelPath: DEFAULT_PATCHES_ROOT_REL_PATH,
		variants: DEFAULT_VARIANTS,
		quality: 82,
		processorName: "auto",
		includeUnreferenced: false,
		force: false,
		reuseExisting: true,
		maxMediaFiles: null,
		actorDiscordId: null,
		envFileRelPath: ".env",
		databaseUrl: null,
		loadEnvFile: true,
		overrideEnvFile: false,
	};

	for (let index = 0; index < argv.length; index += 1) {
		const arg = argv[index];

		if (arg === "--help" || arg === "-h") {
			printUsage();
			process.exit(0);
		}

		if (arg === "--skip-env-file") {
			options.loadEnvFile = false;
			continue;
		}

		if (arg === "--override-env-file") {
			options.overrideEnvFile = true;
			continue;
		}

		if (arg === "--include-unreferenced") {
			options.includeUnreferenced = true;
			continue;
		}

		if (arg === "--force") {
			options.force = true;
			continue;
		}

		if (arg === "--no-reuse") {
			options.reuseExisting = false;
			continue;
		}

		const valueArgNames = new Set([
			"--patch",
			"--scan-batch-id",
			"--patches-root",
			"--variants",
			"--quality",
			"--processor",
			"--max",
			"--actor-discord-id",
			"--env-file",
			"--database-url",
		]);

		if (!valueArgNames.has(arg)) {
			throw new Error(`Unknown argument: ${arg}`);
		}

		const value = argv[index + 1];
		if (!value || value.startsWith("--")) {
			throw new Error(`Missing value for ${arg}`);
		}

		index += 1;

		if (arg === "--patch") {
			options.patchCode = value.trim();
			continue;
		}

		if (arg === "--scan-batch-id") {
			options.scanBatchId = parsePositiveInteger(value, "scan batch ID");
			continue;
		}

		if (arg === "--patches-root") {
			options.patchesRootRelPath = normalizeRelPath(value.trim());
			continue;
		}

		if (arg === "--variants") {
			options.variants = parseVariants(value);
			continue;
		}

		if (arg === "--quality") {
			options.quality = parseQuality(value);
			continue;
		}

		if (arg === "--processor") {
			const processorName = value.trim().toLowerCase();
			if (!SUPPORTED_PROCESSORS.has(processorName)) {
				throw new Error(`Unsupported processor: ${value}`);
			}
			options.processorName = processorName;
			continue;
		}

		if (arg === "--max") {
			options.maxMediaFiles = parsePositiveInteger(value, "max");
			continue;
		}

		if (arg === "--actor-discord-id") {
			options.actorDiscordId = value.trim();
			continue;
		}

		if (arg === "--env-file") {
			options.envFileRelPath = value.trim();
			continue;
		}

		if (arg === "--database-url") {
			options.databaseUrl = value.trim();
		}
	}

	if (!options.patchCode) {
		throw new Error("Missing required --patch value.");
	}

	assertSafeRelPath(options.patchCode, "patch code");	
	assertSafeRelPath(options.patchesRootRelPath, "patches root");

	return options;
}

function parsePositiveInteger(value, label) {
	if (!/^\d+$/.test(value.trim())) {
		throw new Error(`Invalid ${label}: ${value}`);
	}

	const parsed = Number.parseInt(value.trim(), 10);
	if (!Number.isSafeInteger(parsed) || parsed <= 0) {
		throw new Error(`Invalid ${label}: ${value}`);
	}

	return parsed;
}

function parseQuality(value) {
	const parsed = parsePositiveInteger(value, "quality");
	if (parsed < 1 || parsed > 100) {
		throw new Error(`Quality must be between 1 and 100: ${value}`);
	}

	return parsed;
}

function parseVariants(value) {
	const variants = [];
	const seenCodes = new Set();

	for (const rawPart of value.split(",")) {
		const part = rawPart.trim();
		if (!part) {
			continue;
		}

		const [rawCode, rawSize] = part.split(":");
		const code = (rawCode || "").trim();
		if (!/^[a-z][a-z0-9_]*$/.test(code)) {
			throw new Error(`Invalid variant code: ${code}`);
		}

		if (seenCodes.has(code)) {
			throw new Error(`Duplicate variant code: ${code}`);
		}

		const maxSizePx = parsePositiveInteger((rawSize || "").trim(), `size for ${code}`);
		variants.push({ code, maxSizePx });
		seenCodes.add(code);
	}

	if (variants.length === 0) {
		throw new Error("At least one derivative variant is required.");
	}

	return variants;
}

function loadEnvFile(relativePath, overrideExisting) {
	const absolutePath = resolve(REPO_ROOT, relativePath);
	if (!existsSync(absolutePath)) {
		return { loaded: false, absolutePath, valueCount: 0 };
	}

	const parsedValues = parseEnvFile(readFileSync(absolutePath, "utf8"));
	let valueCount = 0;
	for (const [key, rawValue] of parsedValues) {
		const value = expandEnvValue(rawValue, { ...process.env, ...Object.fromEntries(parsedValues) });
		if (overrideExisting || !Object.prototype.hasOwnProperty.call(process.env, key)) {
			process.env[key] = value;
			valueCount += 1;
		}
	}

	return { loaded: true, absolutePath, valueCount };
}

function parseEnvFile(content) {
	const rows = [];
	for (const rawLine of content.split(/\r?\n/)) {
		const trimmedLine = rawLine.trim();
		if (!trimmedLine || trimmedLine.startsWith("#")) {
			continue;
		}

		const line = trimmedLine.startsWith("export ") ? trimmedLine.slice(7).trim() : trimmedLine;
		const separatorIndex = findEnvSeparator(line);
		if (separatorIndex <= 0) {
			continue;
		}

		const key = line.slice(0, separatorIndex).trim();
		if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(key)) {
			continue;
		}

		const rawValue = stripEnvInlineComment(line.slice(separatorIndex + 1).trim());
		rows.push([key, unquoteEnvValue(rawValue)]);
	}

	return rows;
}

function findEnvSeparator(line) {
	let quote = null;
	for (let index = 0; index < line.length; index += 1) {
		const char = line[index];
		if ((char === "\"" || char === "'") && line[index - 1] !== "\\") {
			quote = quote === char ? null : quote || char;
			continue;
		}

		if (char === "=" && quote === null) {
			return index;
		}
	}

	return -1;
}

function stripEnvInlineComment(value) {
	let quote = null;
	for (let index = 0; index < value.length; index += 1) {
		const char = value[index];
		if ((char === "\"" || char === "'") && value[index - 1] !== "\\") {
			quote = quote === char ? null : quote || char;
			continue;
		}

		if (char === "#" && quote === null && (index === 0 || /\s/.test(value[index - 1]))) {
			return value.slice(0, index).trimEnd();
		}
	}

	return value;
}

function expandEnvValue(value, values) {
	return value.replace(/\$\{([A-Za-z_][A-Za-z0-9_]*)\}/g, (_match, key) => {
		const replacement = values[key];
		return typeof replacement === "string" ? replacement : "";
	});
}

function unquoteEnvValue(value) {
	if (value.length < 2) {
		return value;
	}

	const first = value[0];
	const last = value[value.length - 1];
	if ((first === "\"" && last === "\"") || (first === "'" && last === "'")) {
		return value.slice(1, -1);
	}

	return value;
}

function resolveDatabaseUrl(explicitUrl) {
	if (explicitUrl) {
		return explicitUrl;
	}

	if (process.env.GAME_DATA_DATABASE_URL) {
		return process.env.GAME_DATA_DATABASE_URL;
	}

	const user = process.env.POSTGRES_USER;
	const password = process.env.POSTGRES_PASSWORD;
	const database = process.env.POSTGRES_DB;
	const host = process.env.CM_POSTGRES_HOST || process.env.POSTGRES_HOST_BIND || "127.0.0.1";
	const port = process.env.CM_POSTGRES_PORT || process.env.POSTGRES_EXTERNAL_PORT || "5432";

	if (user && password && database) {
		return `postgresql://${encodeURIComponent(user)}:${encodeURIComponent(password)}@${host}:${port}/${database}`;
	}

	if (process.env.CM_OWNER_DATABASE_URL) {
		return process.env.CM_OWNER_DATABASE_URL;
	}

	throw new Error(
		"Missing database connection. Set GAME_DATA_DATABASE_URL, POSTGRES_USER/POSTGRES_PASSWORD/POSTGRES_DB, or CM_OWNER_DATABASE_URL.",
	);
}

function normalizeRelPath(path) {
	return path.replace(/\\/g, "/").replace(/^\.\//, "").replace(/^\/+/, "").replace(/\/+$/g, "");
}

function assertSafeRelPath(path, label) {
	if (!path || SAFE_RELATIVE_PATH_PATTERN.test(path.replace(/\\/g, "/"))) {
		throw new Error(`Unsafe ${label}: ${path}`);
	}
}

function assertInsideRoot(path, root, label) {
	const relativePath = relative(root, path).split(sep).join("/");
	if (relativePath.startsWith("../") || relativePath === ".." || relativePath.startsWith("/")) {
		throw new Error(`${label} escapes root: ${path}`);
	}
}

function sha256(bufferOrString) {
	return createHash("sha256").update(bufferOrString).digest("hex");
}

function readImageDimensions(buffer, ext) {
	if (ext === "png") {
		return readPngDimensions(buffer);
	}

	if (ext === "jpg" || ext === "jpeg") {
		return readJpegDimensions(buffer);
	}

	if (ext === "webp") {
		return readWebpDimensions(buffer);
	}

	return { width: null, height: null };
}

function readPngDimensions(buffer) {
	if (buffer.length < 24) {
		return { width: null, height: null };
	}

	const signature = buffer.subarray(0, 8).toString("hex");
	if (signature !== "89504e470d0a1a0a") {
		return { width: null, height: null };
	}

	return {
		width: buffer.readUInt32BE(16),
		height: buffer.readUInt32BE(20),
	};
}

function readJpegDimensions(buffer) {
	if (buffer.length < 4 || buffer[0] !== 0xff || buffer[1] !== 0xd8) {
		return { width: null, height: null };
	}

	let offset = 2;
	while (offset < buffer.length) {
		if (buffer[offset] !== 0xff) {
			offset += 1;
			continue;
		}

		const marker = buffer[offset + 1];
		if (marker === 0xd9 || marker === 0xda) {
			break;
		}

		const size = buffer.readUInt16BE(offset + 2);
		if (size < 2) {
			break;
		}

		if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) {
			return {
				width: buffer.readUInt16BE(offset + 7),
				height: buffer.readUInt16BE(offset + 5),
			};
		}

		offset += 2 + size;
	}

	return { width: null, height: null };
}

function readWebpDimensions(buffer) {
	if (buffer.length < 30 || buffer.subarray(0, 4).toString("ascii") !== "RIFF" || buffer.subarray(8, 12).toString("ascii") !== "WEBP") {
		return { width: null, height: null };
	}

	const chunk = buffer.subarray(12, 16).toString("ascii");
	if (chunk === "VP8X" && buffer.length >= 30) {
		return {
			width: 1 + buffer.readUIntLE(24, 3),
			height: 1 + buffer.readUIntLE(27, 3),
		};
	}

	if (chunk === "VP8 " && buffer.length >= 30) {
		return {
			width: buffer.readUInt16LE(26) & 0x3fff,
			height: buffer.readUInt16LE(28) & 0x3fff,
		};
	}

	if (chunk === "VP8L" && buffer.length >= 25) {
		const bits = buffer.readUInt32LE(21);
		return {
			width: (bits & 0x3fff) + 1,
			height: ((bits >> 14) & 0x3fff) + 1,
		};
	}

	return { width: null, height: null };
}

function calculateTargetSize(sourceWidth, sourceHeight, maxSizePx) {
	if (!sourceWidth || !sourceHeight) {
		return { width: maxSizePx, height: maxSizePx };
	}

	const largestSide = Math.max(sourceWidth, sourceHeight);
	if (largestSide <= maxSizePx) {
		return { width: sourceWidth, height: sourceHeight };
	}

	const scale = maxSizePx / largestSide;
	return {
		width: Math.max(1, Math.round(sourceWidth * scale)),
		height: Math.max(1, Math.round(sourceHeight * scale)),
	};
}

function derivativeRelPathFor(sourceRelPath, variantCode) {
	assertSafeRelPath(sourceRelPath, "source media path");
	const normalizedSourcePath = normalizeRelPath(sourceRelPath);
	const extension = extname(normalizedSourcePath);
	const sourceWithoutExt = extension ? normalizedSourcePath.slice(0, -extension.length) : normalizedSourcePath;
	return normalizeRelPath(join("derived", "media", variantCode, `${sourceWithoutExt}.webp`).split(sep).join("/"));
}

function loadSharp() {
	for (const packagePath of [ROOT_PACKAGE_PATH, WEB_PACKAGE_PATH]) {
		try {
			const packageRequire = createRequire(pathToFileURL(packagePath));
			return packageRequire("sharp");
		} catch (_error) {
			// Try the next package boundary.
		}
	}

	return null;
}

function commandExists(command) {
	const result = spawnSync(command, ["--version"], { encoding: "utf8" });
	return result.status === 0 || result.status === 1;
}

function resolveProcessor(requestedProcessorName) {
	if (requestedProcessorName === "sharp") {
		const sharp = loadSharp();
		if (!sharp) {
			throw new Error("Processor sharp was requested, but the sharp package is not installed.");
		}
		return { name: "sharp", sharp };
	}

	if (requestedProcessorName !== "auto") {
		if (!commandExists(requestedProcessorName)) {
			throw new Error(`Processor ${requestedProcessorName} was requested, but that command was not found in PATH.`);
		}
		return { name: requestedProcessorName, sharp: null };
	}

	const sharp = loadSharp();
	if (sharp) {
		return { name: "sharp", sharp };
	}

	for (const command of ["magick", "convert", "cwebp"]) {
		if (commandExists(command)) {
			return { name: command, sharp: null };
		}
	}

	throw new Error(
		"No image processor found. Install sharp in the repo/web package, or install ImageMagick/cwebp on the host.",
	);
}

async function generateDerivative(processor, sourceAbsPath, outputAbsPath, variant, quality, sourceWidth, sourceHeight) {
	mkdirSync(dirname(outputAbsPath), { recursive: true });

	if (processor.name === "sharp") {
		await processor.sharp(sourceAbsPath)
			.resize({
				width: variant.maxSizePx,
				height: variant.maxSizePx,
				fit: "inside",
				withoutEnlargement: true,
			})
			.webp({ quality, alphaQuality: 100 })
			.toFile(outputAbsPath);
		return;
	}

	if (processor.name === "magick") {
		runImageCommand("magick", [sourceAbsPath, "-auto-orient", "-alpha", "on", "-resize", `${variant.maxSizePx}x${variant.maxSizePx}>`, "-quality", String(quality), outputAbsPath]);
		return;
	}

	if (processor.name === "convert") {
		runImageCommand("convert", [sourceAbsPath, "-auto-orient", "-alpha", "on", "-resize", `${variant.maxSizePx}x${variant.maxSizePx}>`, "-quality", String(quality), outputAbsPath]);
		return;
	}

	if (processor.name === "cwebp") {
		const targetSize = calculateTargetSize(sourceWidth, sourceHeight, variant.maxSizePx);
		runImageCommand("cwebp", ["-quiet", "-q", String(quality), "-alpha_q", "100", "-resize", String(targetSize.width), String(targetSize.height), sourceAbsPath, "-o", outputAbsPath]);
		return;
	}

	throw new Error(`Unsupported resolved processor: ${processor.name}`);
}

function runImageCommand(command, args) {
	const result = spawnSync(command, args, { encoding: "utf8" });
	if (result.status !== 0) {
		const stderr = typeof result.stderr === "string" ? result.stderr.trim() : "";
		const stdout = typeof result.stdout === "string" ? result.stdout.trim() : "";
		throw new Error(`${command} failed: ${stderr || stdout || `exit ${result.status}`}`);
	}
}

async function insertMessage(client, message) {
	const result = await client.query(
		`INSERT INTO game_data.import_messages_f(import_batch_id,
														 patch_id,
														 severity_code,
														 message_code,
														 message_text,
														 import_media_file_id,
														 import_media_derivative_id,
														 source_rel_path,
														 context_json)
		 VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9::jsonb)
		 RETURNING import_message_id`,
		[
			message.importBatchId,
			message.patchId,
			message.severityCode,
			message.messageCode,
			message.messageText,
			message.importMediaFileId || null,
			message.importMediaDerivativeId || null,
			message.sourceRelPath || null,
			JSON.stringify(message.context || {}),
		],
	);

	return result.rows[0].import_message_id;
}

async function getPatch(client, patchCode) {
	const result = await client.query(
		`SELECT patch_id,
				patch_code,
				source_root_rel_path,
				patch_status_code
		 FROM game_data.patches
		 WHERE patch_code = $1`,
		[patchCode],
	);

	if (result.rows.length !== 1) {
		throw new Error(`Patch was not found in game_data.patches: ${patchCode}`);
	}

	return result.rows[0];
}

async function resolveScanBatchId(client, patchId, explicitScanBatchId) {
	if (explicitScanBatchId) {
		const result = await client.query(
			`SELECT import_batch_id
			 FROM game_data.import_batches_f
			 WHERE import_batch_id = $1
			   AND patch_id = $2
			   AND batch_type_code = 'scan'
			   AND batch_status_code = 'completed'`,
			[explicitScanBatchId, patchId],
		);

		if (result.rows.length !== 1) {
			throw new Error(`Completed scan batch was not found for this patch: ${explicitScanBatchId}`);
		}

		return explicitScanBatchId;
	}

	const result = await client.query(
		`SELECT import_batch_id
		 FROM game_data.import_batches_f
		 WHERE patch_id = $1
		   AND batch_type_code = 'scan'
		   AND batch_status_code = 'completed'
		 ORDER BY import_batch_id DESC
		 LIMIT 1`,
		[patchId],
	);

	if (result.rows.length !== 1) {
		throw new Error("No completed scan batch was found for this patch.");
	}

	return Number.parseInt(String(result.rows[0].import_batch_id), 10);
}

async function listSourceMedia(client, patchId, scanBatchId, includeUnreferenced, maxMediaFiles) {
	const limitSql = maxMediaFiles ? "LIMIT $4" : "";
	const params = [patchId, scanBatchId, includeUnreferenced];
	if (maxMediaFiles) {
		params.push(maxMediaFiles);
	}

	const result = await client.query(
		`SELECT import_media_file_id,
				patch_id,
				import_file_id,
				source_rel_path,
				source_format_code,
				source_width_px,
				source_height_px,
				source_hash_sha256,
				referenced_flag,
				media_status_code
		 FROM game_data.import_media_files_f
		 WHERE patch_id = $1
		   AND import_batch_id = $2
		   AND media_status_code IN ('found', 'referenced')
		   AND ($3::boolean = true OR referenced_flag = true)
		 ORDER BY referenced_flag DESC,
				  source_rel_path
		 ${limitSql}`,
		params,
	);

	return result.rows;
}

